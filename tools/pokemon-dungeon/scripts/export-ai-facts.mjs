// Data-only projection. No game module is imported or executed.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';

const source = new URL('../content/steel/ai-facts.json', import.meta.url);
const destination = new URL('../../../games/pokemon-dungeon-reimagined/content/ai-facts.js', import.meta.url);
const bytes = await readFile(source);
const facts = JSON.parse(bytes);
assert.equal(facts.schemaVersion, 1);
assert.equal(facts.id, 'original-blue-qualified-ai-facts-v1');
assert.equal(facts.actions.length, 413);
assert.deepEqual(facts.regularAttackWeights, [100, 20, 30, 40, 50]);
assert.equal(facts.confusedAttackSkipPercent, 70);
for (const [i, row] of facts.actions.entries()) {
  assert.deepEqual(Object.keys(row).sort(), ['actionId', 'cannotHitFrozen', 'conditionChance', 'ignoresTaunted', 'targetFlags', 'weight']);
  assert.equal(row.actionId, i);
  for (const key of ['weight', 'conditionChance']) assert(Number.isInteger(row[key]) && row[key] >= 0 && row[key] <= 255);
  assert(Number.isInteger(row.targetFlags) && row.targetFlags >= 0 && row.targetFlags <= 65535);
  for (const key of ['cannotHitFrozen', 'ignoresTaunted']) assert.equal(typeof row[key], 'boolean');
}
const hash = createHash('sha256').update(bytes).digest('hex');
const output = `// Generated by export-ai-facts.mjs. Original Red comparative, not Blue binary proof.
// Authoring SHA-256: ${hash}; provenance: tools/pokemon-dungeon/content/steel/ai-facts.json.
// These are AI targeting flags, distinct from a move's actual execution geometry.
/** @type {ReadonlyArray<Readonly<{actionId:number,weight:number,targetFlags:number,conditionChance:number,cannotHitFrozen:boolean,ignoresTaunted:boolean}>>} */
export const AI_ACTION_FACTS = Object.freeze(${JSON.stringify(facts.actions)}.map(row => Object.freeze(row)));
export const REGULAR_ATTACK_WEIGHTS = Object.freeze(${JSON.stringify(facts.regularAttackWeights)});
export const CONFUSED_ATTACK_SKIP_PERCENT = ${facts.confusedAttackSkipPercent};
export const WILD_ACTIVE_IQ = Object.freeze(${JSON.stringify(facts.wildIq.always)});
export const WILD_ITEM_MASTER_MIN_LEVEL = ${facts.wildIq.minimumItemMasterLevel};
`;
assert(Buffer.byteLength(output) < 1048576);
if (process.argv.includes('--check')) assert.equal(await readFile(destination, 'utf8'), output, 'Stale AI factual projection');
else await writeFile(destination, output);
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Exported'} 413 qualified AI action facts; no game code executed.`);
